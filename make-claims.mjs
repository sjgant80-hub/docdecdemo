// make-claims.mjs — write claims.json from DocDec v2's OWN shipped record, so kar-buildcurve can read the
// claims signal. The page renders these same verdicts client-side from data/v2/record.json; this serialises
// them to a file. Nothing is typed by hand: every pass/fail is read straight from the record. `--check` fails
// if claims.json is not what the record currently forces, so the file can never drift from the record.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(HERE, p), 'utf8');

export function build() {
  const R = JSON.parse(read('data/v2/record.json'));
  let MEAS = null; try { MEAS = JSON.parse(read('data/v2/measured.json')); } catch { /* optional */ }
  const rows = Object.entries(R.claims).map(([id, c]) => ({ id, pass: c.pass === true }));
  if (MEAS && MEAS.c8) rows.push({ id: 'C8', pass: MEAS.c8.pass === true }); // the local-only measured claim, as the page counts it
  const passed = rows.filter((r) => r.pass).length;
  return { build: 'docdecdemo', passed, total: rows.length,
    source: 'generated by make-claims.mjs from data/v2/record.json (+ measured.json for C8) — the page renders the same verdicts',
    claims: rows };
}

export const json = () => JSON.stringify(build(), null, 2) + '\n';

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const j = json();
  if (process.argv.includes('--check')) {
    const cur = (() => { try { return read('claims.json'); } catch { return ''; } })();
    if (cur !== j) { console.error('claims.json is stale — run: node make-claims.mjs'); process.exit(1); }
    console.log('claims.json is current:', build().passed + '/' + build().total);
  } else { writeFileSync(join(HERE, 'claims.json'), j); console.log('wrote claims.json', build().passed + '/' + build().total); }
}
